<#
Wraps a PowerShell script into a single, self-contained, self-elevating .bat
that runs on a locked-down machine without needing a second file or hitting
execution-policy restrictions. Built 2026-09-08 out of a BellCommander
crash case on a client's locked-down file server.

Why this exists instead of the usual Run-X.bat + X.ps1 pair used by tools
1-4 in this folder:
  - A GPO-enforced execution policy blocks "-File script.ps1" outright, and
    the command-line "-ExecutionPolicy Bypass" flag CANNOT override a policy
    set by Group Policy (GPO always wins over that switch). The usual two-
    file .bat pattern relies on that flag and can fail on a machine with a
    locked-down policy.
  - Two files sent separately to a client machine are fragile in practice -
    wrong folder, wrong account's Desktop/Downloads, a browser silently
    appending ".txt" to the .ps1, a typo between the .bat's expected
    filename and the actually-delivered one. All of these produce a
    confusing PowerShell exception pointing at a path that "looks right."

This embeds the target .ps1's full text as a single in-memory PowerShell
command (base64 of UTF-16LE, passed via -EncodedCommand) inside the .bat
itself. Nothing is ever loaded from a .ps1 file at run time, so the GPO
execution-policy check for script files never triggers - and there is only
one file to send, so there is nothing left to mismatch.

USAGE:
  .\New-SelfContainedBat.ps1 -ScriptPath .\MyDiagnostic.ps1
  .\New-SelfContainedBat.ps1 -ScriptPath .\MyDiagnostic.ps1 -OutputPath .\Run-MyDiagnostic.bat -NoElevate

Produces a .bat that:
  - self-elevates via UAC (unless -NoElevate), same pattern as this folder's
    other launchers
  - also passes -ExecutionPolicy Bypass, as a no-op fallback for machines
    where the policy is set locally rather than by GPO (harmless either way)
  - always pauses at the end and prints the PowerShell exit code, so a
    failure is visible instead of a window flashing shut

cmd.exe caps a single command line at ~8191 characters. Base64 of a
PowerShell script runs about 2.7x its source character count (UTF-16, then
base64), so this refuses to build past a source size that would risk that
limit - shorten the source script (shorter variable/function names, fewer
comments and blank lines, terser output strings) if it's rejected. There is
no way around this limit for a single-line embed; splitting a script across
multiple -EncodedCommand invocations is possible but adds real complexity
for what has so far been a rare case - not built here.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string]$ScriptPath,
    [string]$OutputPath,
    [switch]$NoElevate
)

$ScriptPath = (Resolve-Path -LiteralPath $ScriptPath).Path
if (-not $OutputPath) {
    $baseName = [System.IO.Path]::GetFileNameWithoutExtension($ScriptPath)
    $OutputPath = Join-Path (Split-Path $ScriptPath -Parent) "$baseName.bat"
}

# --- Validate the source parses before embedding it ---
$sourceText = Get-Content -Raw -LiteralPath $ScriptPath
try {
    $null = [ScriptBlock]::Create($sourceText)
} catch {
    throw "SYNTAX ERROR in $ScriptPath - fix this before wrapping it: $($_.Exception.Message)"
}

# --- Encode as -EncodedCommand expects: base64 of UTF-16LE text ---
$bytes = [System.Text.Encoding]::Unicode.GetBytes($sourceText)
$b64 = [Convert]::ToBase64String($bytes)
$prefixLen = "powershell -NoProfile -ExecutionPolicy Bypass -EncodedCommand ".Length
$totalLen = $b64.Length + $prefixLen

Write-Host "Source: $($sourceText.Length) chars -> Base64: $($b64.Length) chars -> command line: ~$totalLen chars"
if ($totalLen -gt 8100) {
    throw "Encoded command is ~$totalLen chars, over cmd.exe's ~8191-char line limit. Shorten $ScriptPath (shorter names, fewer comments/blank lines, terser output strings) and try again."
} elseif ($totalLen -gt 6500) {
    Write-Warning "Encoded command is ~$totalLen chars - under the ~8191 limit but with less margin than ideal. Fine to proceed, but trim further if this script grows."
}

# --- Build the .bat ---
$elevateBlock = if ($NoElevate) { @() } else {
    @(
        'net session >nul 2>&1',
        'if %errorlevel% neq 0 (',
        '    echo Requesting administrator privileges...',
        "    powershell -NoProfile -Command ""Start-Process -FilePath '%~f0' -Verb RunAs""",
        '    exit /b',
        ')',
        ''
    )
}

$batLines = @(
    '@echo off',
    "REM Self-contained launcher for $(Split-Path $ScriptPath -Leaf) - generated by",
    'REM New-SelfContainedBat.ps1 (remote-diagnostics/). Runs the script as an',
    'REM embedded in-memory command - no .ps1 file is loaded at run time, so',
    'REM GPO-locked execution policy and missing/mismatched second-file problems',
    'REM both do not apply.',
    ''
) + $elevateBlock + @(
    "powershell -NoProfile -ExecutionPolicy Bypass -EncodedCommand $b64",
    'set RC=%errorlevel%',
    '',
    'echo.',
    'echo ----------------------------------------------------------------',
    'echo PowerShell exit code: %RC%',
    'if %RC% neq 0 (',
    '    echo.',
    '    echo That is not 0 - scroll up and copy the red error text.',
    ')',
    'echo ----------------------------------------------------------------',
    'pause'
)

$batLines -join "`r`n" | Set-Content -LiteralPath $OutputPath -Encoding ascii -NoNewline

# --- Verify: extract the encoded command back out and confirm it decodes to
#     an exact match of the source, so a bad copy/paste never ships silently ---
$batContent = Get-Content -Raw -LiteralPath $OutputPath
if ($batContent -match '-EncodedCommand (\S+)') {
    $decoded = [System.Text.Encoding]::Unicode.GetString([Convert]::FromBase64String($Matches[1]))
    if ($decoded -ne $sourceText) {
        throw "VERIFICATION FAILED: $OutputPath does not decode back to $ScriptPath exactly. Do not send this file."
    }
} else {
    throw "VERIFICATION FAILED: could not find -EncodedCommand in $OutputPath."
}

Write-Host "Built and verified: $OutputPath ($((Get-Item $OutputPath).Length) bytes)" -ForegroundColor Green
Write-Host "Send only this one file - nothing else needed alongside it." -ForegroundColor Green
